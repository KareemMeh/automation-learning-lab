	CONSTRAINT pending_actions_pkey PRIMARY KEY (id),
	CONSTRAINT pending_actions_result_check CHECK (((((status)::text = 'completed'::text) AND (result_ticket_id IS NOT NULL) AND (completed_at IS NOT NULL)) OR (((status)::text <> 'completed'::text) AND (result_ticket_id IS NULL) AND (completed_at IS NULL)))),
	CONSTRAINT pending_actions_status_check CHECK (((status)::text = ANY ((ARRAY['pending'::character varying, 'completed'::character varying, 'cancelled'::character varying, 'expired'::character varying])::text[]))),
	CONSTRAINT pending_actions_type_check CHECK (((action_type)::text = 'create_support_ticket'::text)),
	CONSTRAINT pending_actions_customer_id_fkey FOREIGN KEY (customer_id) REFERENCES public.customers(id),
	CONSTRAINT pending_actions_result_ticket_id_fkey FOREIGN KEY (result_ticket_id) REFERENCES public.support_tickets(id)
);